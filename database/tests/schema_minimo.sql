-- Esquema mínimo para probar 33_cambiar_mesa.sql en un Postgres descartable.
-- Replica solo las columnas/constraints de producción que la función usa.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN CREATE ROLE anon; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN CREATE ROLE authenticated; END IF;
END $$;

DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;

CREATE TABLE public.tenants (id uuid PRIMARY KEY DEFAULT gen_random_uuid());
CREATE TABLE public.usuarios (id uuid PRIMARY KEY DEFAULT gen_random_uuid());

CREATE TABLE public.mesas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
  numero integer NOT NULL CHECK (numero > 0),
  nombre text,
  capacidad integer NOT NULL DEFAULT 4,
  estado text NOT NULL DEFAULT 'libre' CHECK (estado IN ('libre', 'ocupada', 'reservada', 'bloqueada')),
  activa boolean NOT NULL DEFAULT true,
  orden integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, numero)
);

CREATE TABLE public.pedidos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.tenants(id),
  mesa_id uuid REFERENCES public.mesas(id) ON DELETE SET NULL,
  numero_pedido integer,
  total numeric NOT NULL DEFAULT 0,
  estado text NOT NULL DEFAULT 'pendiente',
  estado_pedido text NOT NULL DEFAULT 'FACT',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.mesa_uniones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.tenants(id),
  estado text NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'cerrada'))
);
CREATE TABLE public.mesa_union_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.tenants(id),
  union_id uuid NOT NULL REFERENCES public.mesa_uniones(id),
  mesa_id uuid NOT NULL REFERENCES public.mesas(id)
);
CREATE TABLE public.pedido_divisiones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.tenants(id),
  pedido_padre_id uuid NOT NULL REFERENCES public.pedidos(id),
  pedido_hijo_id uuid NOT NULL REFERENCES public.pedidos(id),
  monto numeric NOT NULL DEFAULT 0
);

CREATE TABLE public.mesa_eventos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES public.tenants(id),
  mesa_id uuid REFERENCES public.mesas(id) ON DELETE SET NULL,
  pedido_id uuid REFERENCES public.pedidos(id) ON DELETE SET NULL,
  usuario_id uuid REFERENCES public.usuarios(id) ON DELETE SET NULL,
  tipo text NOT NULL CHECK (tipo IN (
    'crear_mesa','editar_mesa','ocupar_mesa','liberar_mesa','bloquear_mesa','reservar_mesa',
    'cancelar_reserva','confirmar_reserva','mover_pedido','unir_mesas','cerrar_union','dividir_cuenta')),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
